export function normalizeGuSlug(name: string): string {
  let text = name.toLowerCase().trim();
  text = text.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/đ/g, "d").replace(/Đ/g, "D");
  text = text.replace(/\b(nhat|nhi|tam|tu|ngu|luc|that|bat|cuu)\s+chuyen\b/gi, "");
  text = text.replace(/\b(tien\s+co|tien|co)\b/gi, "");
  text = text.replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  return text;
}


package ws

import (
	"context"
	"encoding/json"
	"time"

	"github.com/google/uuid"
	"github.com/vippro67/GuWorld/backend/internal/realtime/protocol"
	"github.com/vippro67/GuWorld/backend/internal/realtime/sim"
)

// WSMessage is the envelope for all WebSocket messages.
type WSMessage struct {
	Type       string          `json:"type"`
	Channel    string          `json:"channel,omitempty"`
	Payload    json.RawMessage `json:"payload,omitempty"`
	Raw        []byte          `json:"-"`
	Version    int             `json:"version,omitempty"`
	RequestID  string          `json:"request_id,omitempty"`
	V          int             `json:"v,omitempty"`
	Action     string          `json:"-"`
	ReceivedAt time.Time       `json:"-"`
}

// SubscribeMsg is sent by the client to subscribe to a channel.
type SubscribeMsg struct {
	Channel string `json:"channel"`
}

// ChatSendMsg is a generic chat message sent by the client.
type ChatSendMsg struct {
	Content string `json:"content"`
}

// EventMsg is the payload structure sent from Server to Client.
type EventMsg struct {
	Type    string      `json:"type"`
	Channel string      `json:"channel"`
	Data    interface{} `json:"data"`
}

// RealtimeWorldAdmission binds a verified player to a server-created zone
// session. Controller IDs are generated by the server for each WebSocket.
type RealtimeWorldAdmission interface {
	Join(ctx context.Context, playerID, controllerID uuid.UUID, request protocol.JoinRequest) (any, error)
	Input(playerID, controllerID uuid.UUID, input protocol.Input) error
	MoveTarget(playerID, controllerID uuid.UUID, target protocol.MoveTarget) error
	Cast(playerID, controllerID uuid.UUID, cast protocol.Cast) error
	BasicAttack(playerID, controllerID uuid.UUID, attack protocol.Attack) error
	SubscribeSnapshots(playerID, controllerID uuid.UUID) (<-chan sim.Snapshot, func(), error)
	TransferAtEdge(playerID, controllerID uuid.UUID, position sim.Vec2) (protocol.Transfer, bool, error)
	BeginTeleport(playerID uuid.UUID) (bool, error)
	AbortTeleport(playerID uuid.UUID)
	FinishTeleport(playerID uuid.UUID)
	PlayerLocation(playerID uuid.UUID) (regionID string, x, y int, ok bool)
	Leave(playerID, controllerID uuid.UUID) error
	Disconnect(playerID, controllerID uuid.UUID)
}
